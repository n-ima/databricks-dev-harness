import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { checkDelivery, reviewHash, digest } from '../../tools/lib/delivery-assurance.mjs';
import { sealEvidence } from '../../tools/lib/evidence.mjs';
const c=JSON.parse(await readFile('work/quality/2026-09-16-publication-review-ready.json'));
const reviewPath='work/reviews/2026-09-16-publication-acceptance.json';
const review=JSON.parse(await readFile(reviewPath));
assert.equal(review.independent,true);
assert.equal(review.reviewedSha256,reviewHash(c));
assert.equal(review.acceptance.length,c.requirements.length);
assert.ok(review.acceptance.every(a=>a.status==='pass'&&c.requirements.includes(a.id)));
const ref=async path=>({path,sha256:digest(await readFile(path))});
c.reviews=[{actor:review.reviewer,context:review.context,independent:true,status:'pass',reviewedSha256:review.reviewedSha256,coverage:review.coverage,evidence:await Promise.all([reviewPath,'work/reviews/2026-09-16-publication-acceptance.md'].map(ref))}];
const report=await checkDelivery(process.cwd(),c,{phase:'verify'});
assert.deepEqual(report.findings,[]);
const accepted='work/quality/2026-09-16-publication-accepted.json',reportPath='work/evidence/2026-09-16-publication-accepted-check.json';
await writeFile(accepted,JSON.stringify(c,null,2)+'\n',{flag:'wx'});
await writeFile(reportPath,JSON.stringify(report,null,2)+'\n',{flag:'wx'});
const hidden=JSON.parse(await readFile('work/evidence/2026-09-16-publication-provider-ci-snapshot.json'));
for(const file of hidden.snapshots)assert.equal(digest(await readFile(file.path)),file.sha256);
const receipt=await sealEvidence(process.cwd(),{review:reviewPath,session:'20260916-010024-987-harness-publication-contract',requirement:c.requirement.path,artifact:[...c.artifacts.map(a=>a.path),...hidden.snapshots.map(a=>a.path),accepted,reportPath]});
console.log(JSON.stringify({report,receiptStatus:receipt.status,remotePush:false},null,2));
